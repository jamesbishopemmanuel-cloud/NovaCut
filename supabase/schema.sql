create table if not exists public.ai_generation_history (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  type text not null check (type in ('Image', 'Video', 'Music')),
  model text not null,
  prompt text not null default '',
  task_id text not null default '',
  status text not null default 'Submitted',
  response text not null default '',
  created_at timestamptz not null default now()
);

alter table public.ai_generation_history enable row level security;
grant select, insert, update, delete on public.ai_generation_history to authenticated;
grant usage, select on sequence public.ai_generation_history_id_seq to authenticated;

drop policy if exists "Users read own AI history" on public.ai_generation_history;
create policy "Users read own AI history" on public.ai_generation_history
  for select to authenticated using (auth.uid() = user_id);

drop policy if exists "Users insert own AI history" on public.ai_generation_history;
create policy "Users insert own AI history" on public.ai_generation_history
  for insert to authenticated with check (auth.uid() = user_id);

drop policy if exists "Users update own AI history" on public.ai_generation_history;
create policy "Users update own AI history" on public.ai_generation_history
  for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "Users delete own AI history" on public.ai_generation_history;
create policy "Users delete own AI history" on public.ai_generation_history
  for delete to authenticated using (auth.uid() = user_id);
